/**
 * Generates supabase/seed.sql from the example party defined in TypeScript
 * (src/data/defaults.ts), so there are never two versions of the same data.
 * Uses esbuild, which already ships with Vite.
 *
 *   node scripts/generate-seed.mjs
 */
import { build } from 'esbuild'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const bundle = await build({
  entryPoints: [resolve(root, 'src/data/defaults.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'neutral',
  alias: { '@': resolve(root, 'src') },
})

const code = bundle.outputFiles[0].text
const module = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)

// Fixed ids: that way the seed can be re-run without duplicating anything.
const IDS = [
  'a1000000-0000-4000-8000-000000000001',
  'a1000000-0000-4000-8000-000000000002',
  'a1000000-0000-4000-8000-000000000003',
  'a1000000-0000-4000-8000-000000000004',
  'a1000000-0000-4000-8000-000000000005',
  'a1000000-0000-4000-8000-000000000006',
  'a1000000-0000-4000-8000-000000000007',
  'a1000000-0000-4000-8000-000000000008',
]

const roster = module.demoRoster().map((character, i) => ({
  ...character,
  id: IDS[i] ?? character.id,
}))

const quote = (value) => `'${String(value).replace(/'/g, "''")}'`

const rows = roster
  .map((c) => `  (${quote(c.id)}, ${quote(c.identity.name)}, ${quote(JSON.stringify(c))}::jsonb)`)
  .join(',\n')

const quests = module.demoQuests(roster)

const sqlArray = (items) => `array[${items.map(quote).join(', ')}]::text[]`
const questRows = quests.quests
  .map((q) => `  (${quote(q.id)}, ${quote(q.scope)}, ${quote(q.status)}, ${quote(q.title)}, ${quote(q.description)}, ${quote(q.giver)}, ${quote(q.location)}, ${q.recommendedLevel ?? 'null'}, ${quote(JSON.stringify(q.rewardCoins))}::jsonb, ${q.rewardXp}, ${sqlArray(q.rewardItems)}, ${quote(q.createdAt)})`)
  .join(',\n')
const objectiveRows = quests.objectives
  .map((o) => `  (${quote(o.id)}, ${quote(o.questId)}, ${o.position}, ${quote(o.text)}, ${o.target}, ${o.progress})`)
  .join(',\n')
const participantRows = quests.participants
  .map((p) => `  (${quote(p.questId)}, ${quote(p.characterId)}, ${p.joined}, ${p.tracked})`)
  .join(',\n')

const sql = `-- ARCANA · example party
-- Generated by scripts/generate-seed.mjs from src/data/defaults.ts.
-- Do not edit by hand: re-run the script if the data changes.
--
-- Run AFTER supabase/migrations/0001_init.sql (the quest part also needs 0002_quests.sql).
-- Safe to run several times: rows that already exist are ignored.
--
-- owner_id is left null on purpose: these characters belong to the table, not
-- to one account, and every user has the same permissions.

insert into public.characters (id, name, data) values
${rows}
on conflict (id) do nothing;

-- Example quests (run AFTER supabase/migrations/0002_quests.sql).

insert into public.quests (id, scope, status, title, description, giver, location, recommended_level, reward_coins, reward_xp, reward_items, created_at) values
${questRows}
on conflict (id) do nothing;

insert into public.quest_objectives (id, quest_id, position, text, target, progress) values
${objectiveRows}
on conflict (id) do nothing;
${participantRows ? `
insert into public.quest_participants (quest_id, character_id, joined, tracked) values
${participantRows}
on conflict (quest_id, character_id) do nothing;
` : ''}`

mkdirSync(resolve(root, 'supabase'), { recursive: true })
writeFileSync(resolve(root, 'supabase/seed.sql'), sql)
console.log(`Wrote supabase/seed.sql with ${roster.length} characters and ${quests.quests.length} quests.`)
